const PT_EXACT_KEYS = new Set(['Off', 'Rest', 'Test', 'Week', 'Progress', 'lb', 'of', 'all', 'breakfast', 'lunch', 'dinner', 'snack', '— none —', "Browser", "Decline", "Unsync", "List", "Prep", "Plan", "Kitchen", "Workout", "This week", "Upper", "Lower", "Full body", "Mixed", "Gym card", "Body stats", "Recent PRs", "Required", "You", "Food", "Name", "Plain HTTP", "Direct connection", "Account", "Administrator", "Owner", "Remove", "Security", "Scan", "Approve", "Unlock", "Swap", "Today"]);
const PT_PAIRS = Object.entries(PT_PHRASES)
  .filter(([from]) => !PT_EXACT_KEYS.has(from))
  .sort((a, b) => b[0].length - a[0].length);
function pt(text) {
  if (!text || !/[A-Za-z]/.test(text)) return text;
  const trimmed = text.trim();
  if (PT_EXACT_KEYS.has(trimmed)) return text.replace(trimmed, PT_PHRASES[trimmed]);
  let translated = text;
  for (const [from, to] of PT_PAIRS) translated = translated.replaceAll(from, to);
  // Compact labels used throughout the training UI.
  translated = translated.replace(/\brepeti(?:ção|ções)\b/gi, 'rep.');
  translated = translated.replace(/\bBF\b/g, 'GC');
  return translated;
}
function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const translated = pt(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const attr of ['placeholder', 'title', 'aria-label', 'alt']) {
    if (node.hasAttribute(attr)) node.setAttribute(attr, pt(node.getAttribute(attr)));
  }
  node.childNodes.forEach(translateNode);
}
