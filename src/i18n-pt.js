const PT_PAIRS = Object.entries(PT_PHRASES).sort((a, b) => b[0].length - a[0].length);
function pt(text) {
  if (!text || !/[A-Za-z]/.test(text)) return text;
  let translated = text;
  for (const [from, to] of PT_PAIRS) translated = translated.replaceAll(from, to);
  return translated;
}
function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const translated = pt(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const attr of ['placeholder', 'title', 'aria-label', 'alt']) {
    if (node.hasAttribute(attr)) node.setAttribute(attr, pt(node.getAttribute(attr)));
  }
  node.childNodes.forEach(translateNode);
}
function translateForge90() { translateNode(document.documentElement); document.documentElement.lang = 'pt-BR'; }
new MutationObserver(records => records.forEach(record => record.addedNodes.forEach(translateNode)))
  .observe(document.documentElement, { childList: true, subtree: true });
